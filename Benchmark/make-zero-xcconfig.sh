#!/usr/bin/env bash
# Point the BenchZero target at a packaged HotSpot Zero runtime.
#
# Usage: make-zero-xcconfig.sh <packaged-runtime>
#
# <runtime> must contain lib/lib/modules and native/<sdk>/lib*.a, which is what
# a Zero build produces once its static libraries and jlinked image are packaged
# (for example moeReader's SuwayomiHost/jvm-ios/package.sh).
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
[[ $# -eq 1 ]] || { echo "usage: $(basename "$0") <packaged-runtime>" >&2; exit 2; }
RUNTIME=$(cd "$1" && pwd)
[[ -f "$RUNTIME/lib/lib/modules" ]] || { echo "$RUNTIME/lib/lib/modules is missing" >&2; exit 1; }

SDK=iphonesimulator
[[ -d "$RUNTIME/native/$SDK" ]] || SDK=iphoneos
NATIVE="$RUNTIME/native/$SDK"
[[ -d "$NATIVE" ]] || { echo "$RUNTIME/native/<sdk> is missing" >&2; exit 1; }

{
    echo "// Generated by make-zero-xcconfig.sh from $NATIVE; do not edit."
    echo "DEAD_CODE_STRIPPING = NO"
    echo "OTHER_LDFLAGS = \\"
    for archive in "$NATIVE"/lib*.a; do
        echo "  -force_load $archive \\"
    done
    echo "  -lz -lc++ \\"
    if [[ -s "$NATIVE/external-flags.txt" ]]; then
        sed -e 's/[[:space:]]*$//' -e 's/$/ \\/' "$NATIVE/external-flags.txt"
    else
        echo "  -framework Foundation -framework CoreFoundation \\"
    fi
    echo "  -Wl,-undefined,dynamic_lookup"
    echo "// The jlinked image is copied into the app bundle by the build script."
    echo "ZERO_RUNTIME = $RUNTIME"
} >"$HERE/zero.xcconfig"
echo "wrote $HERE/zero.xcconfig ($SDK archives)"
