#!/usr/bin/env bash
# Build and run the benchmark against a statically linked HotSpot Zero runtime
# in the iOS Simulator.
#
# Usage: bench-zero-sim.sh --runtime <dir> [--out <dir>] [--timeout <seconds>]
#
# <dir> is the packaged Zero runtime: it must contain lib/ (the jlinked image,
# including lib/lib/modules) and native/iphonesimulator/ with lib*.a plus
# external-flags.txt, as produced by moeReader's SuwayomiHost/jvm-ios/package.sh.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
APP_DIR="$ROOT/Samples/HelloZero"
RUNTIME=""
OUT="$ROOT/work/bench-zero-sim"
TIMEOUT=900
BUNDLE_ID=org.openj9.ios.HelloZero

usage() {
    echo "Usage: $(basename "$0") --runtime <packaged-zero-runtime> [--out <dir>] [--timeout <seconds>]"
    echo "Requires Xcode, XcodeGen, python3 and a host JDK 21 (HOST_JAVA_HOME or JAVA_HOME)."
}

die() { echo "bench-zero-sim.sh: $*" >&2; exit 1; }
while [[ $# -gt 0 ]]; do
    case "$1" in
        -h|--help) usage; exit 0 ;;
        --runtime|--out|--timeout)
            [[ $# -ge 2 && -n "$2" ]] || die "$1 requires a value"
            case "$1" in
                --runtime) RUNTIME=$2 ;;
                --out) OUT=$2 ;;
                --timeout) TIMEOUT=$2 ;;
            esac
            shift 2 ;;
        *) usage >&2; die "unknown argument: $1" ;;
    esac
done
[[ -n "$RUNTIME" ]] || { usage >&2; die "--runtime is required"; }
[[ "$TIMEOUT" =~ ^[1-9][0-9]*$ ]] || die "--timeout must be a positive integer"
RUNTIME=$(cd "$RUNTIME" && pwd)
[[ -f "$RUNTIME/lib/lib/modules" ]] || die "$RUNTIME/lib/lib/modules is missing"
NATIVE="$RUNTIME/native/iphonesimulator"
[[ -d "$NATIVE" ]] || die "$NATIVE is missing (build the simulator slice of Zero)"
for tool in xcrun xcodebuild xcodegen python3; do
    command -v "$tool" >/dev/null 2>&1 || die "required tool not found: $tool"
done
[[ "$(uname -m)" == arm64 ]] || die "arm64 simulator binaries require an Apple Silicon host"
export HOST_JAVA_HOME="${HOST_JAVA_HOME:-${JAVA_HOME:-$(/usr/libexec/java_home -v 21)}}"
[[ -x "$HOST_JAVA_HOME/bin/javac" ]] || die "no host javac at $HOST_JAVA_HOME/bin/javac"

mkdir -p "$OUT"
OUT=$(cd "$OUT" && pwd)
LOG="$OUT/console.log"
BUILD_LOG="$OUT/build.log"
UDID=""
SUCCESS=0
: >"$LOG"

cleanup() {
    status=$?
    trap - EXIT
    if [[ -n "$UDID" ]]; then
        xcrun simctl terminate "$UDID" "$BUNDLE_ID" >/dev/null 2>&1 || true
        xcrun simctl shutdown "$UDID" >/dev/null 2>&1 || true
        xcrun simctl delete "$UDID" >/dev/null 2>&1 || true
    fi
    if [[ "$SUCCESS" != 1 ]]; then
        echo "=== Simulator console (last 120 lines) ===" >&2
        tail -n 120 "$LOG" >&2 || true
        echo "=== Build log (last 60 lines) ===" >&2
        [[ ! -f "$BUILD_LOG" ]] || tail -n 60 "$BUILD_LOG" >&2
        [[ $status -ne 0 ]] || status=1
    fi
    exit "$status"
}
trap cleanup EXIT

# Link flags: every archive is force-loaded so the VM's JNI entry points survive.
XCCONFIG="$APP_DIR/zero-runtime.xcconfig"
{
    echo "// Generated by scripts/bench-zero-sim.sh from $NATIVE; do not edit."
    echo "DEAD_CODE_STRIPPING = NO"
    echo "OTHER_LDFLAGS = \\"
    for archive in "$NATIVE"/lib*.a; do
        echo "  -force_load $archive \\"
    done
    echo "  -lz -lc++ \\"
    if [[ -s "$NATIVE/external-flags.txt" ]]; then
        sed -e 's/[[:space:]]*$//' "$NATIVE/external-flags.txt" | sed -e 's/$/ \\/'
    else
        echo "  -framework Foundation -framework CoreFoundation \\"
    fi
    echo "  -Wl,-undefined,dynamic_lookup"
} >"$XCCONFIG"
trap 'rm -f "$XCCONFIG"; cleanup' EXIT

xcodegen generate --spec "$APP_DIR/project.yml" --project "$APP_DIR" >/dev/null
xcodebuild -project "$APP_DIR/HelloZero.xcodeproj" -scheme HelloZero \
    -configuration Debug -sdk iphonesimulator -destination 'generic/platform=iOS Simulator' \
    -derivedDataPath "$OUT/DerivedData" ARCHS=arm64 ONLY_ACTIVE_ARCH=YES \
    ZERO_RUNTIME="$RUNTIME" HOST_JAVA_HOME="$HOST_JAVA_HOME" \
    CODE_SIGNING_ALLOWED=YES CODE_SIGNING_REQUIRED=YES 'CODE_SIGN_IDENTITY=-' build 2>&1 | tee "$BUILD_LOG"
APP="$OUT/DerivedData/Build/Products/Debug-iphonesimulator/HelloZero.app"
[[ -d "$APP" ]] || die "app was not built: $APP"
[[ -f "$APP/lib/lib/modules" ]] || die "the app bundle has no lib/lib/modules"
[[ -f "$APP/Bench.jar" ]] || die "the app bundle has no Bench.jar"

SELECTION=$(xcrun simctl list --json | python3 - <<'PY'
import json, sys
data = json.load(sys.stdin)
runtimes = [r for r in data['runtimes']
            if r.get('isAvailable') and r['identifier'].startswith('com.apple.CoreSimulator.SimRuntime.iOS-')]
if not runtimes:
    sys.exit('No available iOS simulator runtime; install one in Xcode Settings > Platforms.')
runtime = max(runtimes, key=lambda r: tuple(int(n) for n in r['version'].split('.')))
parts = [int(n) for n in runtime['version'].split('.')]
version = (parts[0] << 16) | ((parts[1] if len(parts) > 1 else 0) << 8) | (parts[2] if len(parts) > 2 else 0)
phones = [d for d in data['devicetypes']
          if d['name'].startswith('iPhone') and d.get('minRuntimeVersion', 0) <= version <= d.get('maxRuntimeVersion', 0xffffffff)]
if not phones:
    sys.exit('No compatible iPhone simulator device type.')
print(runtime['identifier'])
print(phones[-1]['identifier'])
PY
)
RUNTIME_ID=$(printf '%s\n' "$SELECTION" | sed -n '1p')
DEVICE_TYPE=$(printf '%s\n' "$SELECTION" | sed -n '2p')
UDID=$(xcrun simctl create "HelloZero-$$" "$DEVICE_TYPE" "$RUNTIME_ID")
xcrun simctl boot "$UDID"
xcrun simctl bootstatus "$UDID" -b
xcrun simctl install "$UDID" "$APP"

set +e
python3 - "$TIMEOUT" "$UDID" "$BUNDLE_ID" <<'PY' 2>&1 | tee "$LOG"
import os, signal, subprocess, sys
process = subprocess.Popen(['xcrun', 'simctl', 'launch', '--console-pty', '--terminate-running-process',
                            sys.argv[2], sys.argv[3]], start_new_session=True)
try:
    sys.exit(process.wait(timeout=int(sys.argv[1])))
except subprocess.TimeoutExpired:
    os.killpg(process.pid, signal.SIGTERM)
    try:
        process.wait(timeout=10)
    except subprocess.TimeoutExpired:
        os.killpg(process.pid, signal.SIGKILL)
        process.wait()
    print('ZERO_IOS_FAIL: simulator launch timed out', flush=True)
    sys.exit(124)
PY
STATUS=${PIPESTATUS[0]}
set -e
echo "app exit status: $STATUS"

grep -q '^BENCH_HOST ' "$LOG" || die "benchmark host marker missing (see $LOG)"
grep -q '^ZERO_IOS_BENCH_DONE' "$LOG" || die "benchmark did not finish (status $STATUS; see $LOG)"
if grep -q 'ZERO_IOS_FAIL:' "$LOG"; then die "failure marker found (see $LOG)"; fi
echo "=== benchmark results ==="
grep -E '^(BENCH_HOST|BENCH) ' "$LOG"
SUCCESS=1
echo "HotSpot Zero simulator benchmark passed; logs: $OUT"
