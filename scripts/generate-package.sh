#!/usr/bin/env bash
#
# generate-package.sh - (re)write the root Package.swift from a set of
# xcframeworks.
#
# Local mode (default): every binary target points at
#   <local-prefix>/<stem>.xcframework   (default prefix Artifacts/XCFrameworks)
# Remote mode (--remote-base-url + --checksums): every binary target uses
#   url: <base-url>/<stem>.xcframework.zip, checksum: from checksums.txt
# where checksums.txt is the file written by make-xcframeworks.sh
# ("<sha256>  <stem>.xcframework.zip" per line).
#
# The framework list comes from the *.xcframework directories in
# --frameworks-dir, or (without built artifacts) from --frameworks a,b,c.

set -euo pipefail

SCRIPT_NAME=$(basename "$0")
REPO_ROOT=$(cd "$(dirname "$0")/.." && pwd)

usage() {
	cat <<EOF
Usage: $SCRIPT_NAME (--frameworks-dir <dir> | --frameworks a,b,c)
                    [--remote-base-url <url> --checksums <checksums.txt>]
                    [--local-prefix Artifacts/XCFrameworks] [--output <Package.swift>]

  --frameworks-dir   Directory containing the <stem>.xcframework bundles.
  --frameworks       Comma separated framework stems (used instead of --frameworks-dir).
  --remote-base-url  Emit url:/checksum: binary targets; URLs are <base>/<stem>.xcframework.zip.
  --checksums        checksums.txt from make-xcframeworks.sh (required with --remote-base-url).
  --local-prefix     Package-relative directory of the xcframeworks in local mode
                     (default: Artifacts/XCFrameworks).
  --output           File to write (default: $REPO_ROOT/Package.swift).
EOF
}

die() {
	echo "$SCRIPT_NAME: error: $*" >&2
	exit 1
}

usage_error() {
	echo "$SCRIPT_NAME: $*" >&2
	usage >&2
	exit 2
}

FRAMEWORKS_DIR=""
FRAMEWORKS_CSV=""
REMOTE_BASE_URL=""
CHECKSUMS=""
LOCAL_PREFIX="Artifacts/XCFrameworks"
OUTPUT="$REPO_ROOT/Package.swift"

while [[ $# -gt 0 ]]; do
	opt=$1
	case "$opt" in
	-h | --help)
		usage
		exit 0
		;;
	--frameworks-dir | --frameworks | --remote-base-url | --checksums | --local-prefix | --output)
		[[ $# -ge 2 && -n "$2" ]] || usage_error "option $opt requires a value"
		val=$2
		shift 2
		;;
	--*=*)
		val=${opt#*=}
		opt=${opt%%=*}
		shift
		;;
	*)
		usage_error "unknown argument: $opt"
		;;
	esac
	case "$opt" in
	--frameworks-dir) FRAMEWORKS_DIR=$val ;;
	--frameworks) FRAMEWORKS_CSV=$val ;;
	--remote-base-url) REMOTE_BASE_URL=${val%/} ;;
	--checksums) CHECKSUMS=$val ;;
	--local-prefix) LOCAL_PREFIX=${val%/} ;;
	--output) OUTPUT=$val ;;
	*) usage_error "unknown option: $opt" ;;
	esac
done

if [[ -n "$FRAMEWORKS_DIR" && -n "$FRAMEWORKS_CSV" ]]; then
	usage_error "use either --frameworks-dir or --frameworks, not both"
fi
if [[ -z "$FRAMEWORKS_DIR" && -z "$FRAMEWORKS_CSV" ]]; then
	usage_error "--frameworks-dir or --frameworks is required"
fi
if [[ -n "$REMOTE_BASE_URL" && -z "$CHECKSUMS" ]]; then
	usage_error "--remote-base-url requires --checksums"
fi
if [[ -z "$REMOTE_BASE_URL" && -n "$CHECKSUMS" ]]; then
	usage_error "--checksums is only meaningful with --remote-base-url"
fi
case "$LOCAL_PREFIX" in
/*) usage_error "--local-prefix must be relative to the package root" ;;
esac

if [[ -n "$FRAMEWORKS_DIR" ]]; then
	[[ -d "$FRAMEWORKS_DIR" ]] || die "frameworks directory does not exist: $FRAMEWORKS_DIR"
	STEMS=$(for xc in "$FRAMEWORKS_DIR"/*.xcframework; do
		if [[ -d "$xc" ]]; then
			basename "$xc" .xcframework
		fi
	done | LC_ALL=C sort -u)
else
	STEMS=$(echo "$FRAMEWORKS_CSV" | tr ',' '\n' | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' | grep -v '^$' | LC_ALL=C sort -u || true)
fi
[[ -n "$STEMS" ]] || die "no frameworks found"
echo "$STEMS" | grep -qx 'jvm' || die "the framework set must contain jvm"
for stem in $STEMS; do
	[[ "$stem" =~ ^[A-Za-z0-9_][A-Za-z0-9_.+-]*$ ]] || die "invalid framework name: $stem"
done

checksum_for() {
	local sum
	sum=$(awk -v f="$1.xcframework.zip" '$2 == f || $2 == "*" f { print $1; exit }' "$CHECKSUMS")
	[[ "$sum" =~ ^[0-9a-f]{64}$ ]] || die "no valid checksum for $1.xcframework.zip in $CHECKSUMS"
	echo "$sum"
}

if [[ -n "$CHECKSUMS" ]]; then
	[[ -f "$CHECKSUMS" ]] || die "checksums file does not exist: $CHECKSUMS"
	# Validate in this shell: die() inside a $(...) below would only leave a subshell.
	for stem in $STEMS; do
		checksum_for "$stem" >/dev/null
	done
fi

swift_string() {
	# Escape for a Swift string literal.
	local s=${1//\\/\\\\}
	echo "\"${s//\"/\\\"}\""
}

TMP="$OUTPUT.tmp.$$"
trap 'rm -f "$TMP"' EXIT

{
	echo '// swift-tools-version:5.9'
	echo '//'
	echo '// GENERATED by scripts/generate-package.sh - do not edit by hand.'
	echo '// Generated from the selected runtime variant; all binary dependencies'
	echo '// must belong to that same variant.'
	if [[ -n "$REMOTE_BASE_URL" ]]; then
		echo '// Mode: remote binary targets.'
	else
		echo "// Mode: local binary targets under $LOCAL_PREFIX/."
	fi
	echo
	echo 'import PackageDescription'
	echo
	echo 'let package = Package('
	echo '    name: "OpenJ9",'
	echo '    platforms: [.iOS("15.0")],'
	echo '    products: ['
	echo '        .library(name: "OpenJ9", targets: ["OpenJ9Kit"]),'
	echo '    ],'
	echo '    targets: ['
	echo '        .target('
	echo '            name: "OpenJ9Kit",'
	echo '            dependencies: ['
	for stem in $STEMS; do
		echo "                .target(name: $(swift_string "$stem")),"
	done
	echo '            ],'
	echo '            path: "Sources/OpenJ9Kit",'
	echo '            publicHeadersPath: "include",'
	echo '            linkerSettings: ['
	echo '                .linkedFramework("Foundation"),'
	echo '                .linkedFramework("CoreFoundation"),'
	echo '            ]'
	echo '        ),'
	for stem in $STEMS; do
		if [[ -n "$REMOTE_BASE_URL" ]]; then
			echo '        .binaryTarget('
			echo "            name: $(swift_string "$stem"),"
			echo "            url: $(swift_string "$REMOTE_BASE_URL/$stem.xcframework.zip"),"
			echo "            checksum: $(swift_string "$(checksum_for "$stem")")"
			echo '        ),'
		else
			echo "        .binaryTarget(name: $(swift_string "$stem"), path: $(swift_string "$LOCAL_PREFIX/$stem.xcframework")),"
		fi
	done
	echo '    ]'
	echo ')'
} >"$TMP"

mv "$TMP" "$OUTPUT"
trap - EXIT
echo "==> wrote $OUTPUT ($(echo "$STEMS" | wc -l | tr -d ' ') binary targets)"
